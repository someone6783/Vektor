import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, URL } from "node:url";
import process from "node:process";
import { resolve } from "node:path";
import { valid } from "semver";

export const projectRoot = fileURLToPath(new URL("../", import.meta.url));
export function metadata(root = projectRoot) {
  const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
  if (!valid(pkg.version) || valid(pkg.version) !== pkg.version)
    throw new Error("Root package version must be canonical semver.");
  const url = new URL(pkg.repository.url);
  if (
    url.protocol !== "https:" ||
    url.hostname !== "github.com" ||
    url.username ||
    url.password ||
    url.search ||
    url.hash
  )
    throw new Error("Repository must be an HTTPS GitHub URL.");
  const repository = url.pathname.replace(/^\//, "").replace(/\.git$/, "");
  if (!/^[A-Za-z0-9_-]+\/[A-Za-z0-9_.-]+$/.test(repository))
    throw new Error("Invalid release repository.");
  if (typeof pkg.vektor?.releaseRepositoryPrivate !== "boolean")
    throw new Error("Set the release repository visibility explicitly.");
  return {
    version: pkg.version,
    repository,
    repositoryPrivate: pkg.vektor.releaseRepositoryPrivate,
    sourceUrl: `https://github.com/${repository}`,
    image: `ghcr.io/${repository.toLowerCase()}`,
  };
}
export function syncVersion(check = false, root = projectRoot) {
  const info = metadata(root);
  const generated = `// Generated by scripts/version.mjs from the root package metadata.\nexport const APP_VERSION = ${JSON.stringify(info.version)};\nexport const RELEASE_REPOSITORY = ${JSON.stringify(info.repository)};\nexport const RELEASE_REPOSITORY_PRIVATE = ${info.repositoryPrivate};\nexport const RELEASE_SOURCE_URL = ${JSON.stringify(info.sourceUrl)};\nexport const RELEASE_IMAGE = ${JSON.stringify(info.image)};\n`;
  const update = (path, expected) => {
    const absolute = resolve(root, path);
    let current = "";
    try {
      current = readFileSync(absolute, "utf8");
    } catch {
      /* First generation. */
    }
    if (current === expected) return;
    if (check)
      throw new Error(`${path} is stale. Run pnpm version:sync and commit the generated metadata.`);
    writeFileSync(absolute, expected);
  };
  update("packages/shared/src/build-info.ts", generated);
  for (const workspace of ["apps/api", "apps/web", "packages/shared", "packages/db"]) {
    const path = `${workspace}/package.json`;
    const value = JSON.parse(readFileSync(resolve(root, path), "utf8"));
    value.version = info.version;
    update(path, JSON.stringify(value, null, 2) + "\n");
  }
  const cargoPath = "apps/web/src-tauri/Cargo.toml";
  const cargo = readFileSync(resolve(root, cargoPath), "utf8").replace(
    /(\[package\][\s\S]*?\nversion = ")[^"]+("\n)/,
    (_match, prefix, suffix) => `${prefix}${info.version}${suffix}`,
  );
  update(cargoPath, cargo);
  const lockPath = "apps/web/src-tauri/Cargo.lock";
  const lock = readFileSync(resolve(root, lockPath), "utf8").replace(
    /(\[\[package\]\]\nname = "vektor-desktop"\nversion = ")[^"]+("\n)/,
    (_match, prefix, suffix) => `${prefix}${info.version}${suffix}`,
  );
  update(lockPath, lock);
  const dockerPath = "Dockerfile";
  const docker = readFileSync(resolve(root, dockerPath), "utf8")
    .replace(/ARG APP_VERSION=[^\n]+/, `ARG APP_VERSION=${info.version}`)
    .replace(
      /(# BEGIN GENERATED RELEASE LABELS\n)[\s\S]*?(# END GENERATED RELEASE LABELS)/,
      `$1LABEL org.opencontainers.image.version="${info.version}" \\\n      org.opencontainers.image.source="${info.sourceUrl}"\n$2`,
    );
  update(dockerPath, docker);
  const capabilityPath = "apps/web/src-tauri/capabilities/default.json";
  const capability = readFileSync(resolve(root, capabilityPath), "utf8").replace(
    /("url": ")https:\/\/github\.com\/[^" ]+\/releases\/tag\/\*(")/,
    (_match, prefix, suffix) => `${prefix}${info.sourceUrl}/releases/tag/*${suffix}`,
  );
  update(capabilityPath, capability);
  const composePath = "compose.release.yaml";
  const compose = readFileSync(resolve(root, composePath), "utf8").replace(
    /(VEKTOR_IMAGE:-)[^}]+/,
    (_match, prefix) => `${prefix}${info.image}:latest`,
  );
  update(
    composePath,
    compose.replace(
      /(VEKTOR_WEB_IMAGE:-)[^}]+/,
      (_match, prefix) => `${prefix}${info.image}-web:latest`,
    ),
  );
  return info;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  syncVersion(process.argv.includes("--check"));
